#!/usr/bin/env python3
# Writes engine/src/Anode.Interchange/Aaf/AafMetaModel.g.cs: the AAF object model's standard class and type definitions
# (AAF Object Specification v1.1, as pyaaf2 1.7.1 tabulates it in aaf2/model/classdefs.py and typedefs.py, MIT), which
# Anode's AAF writer stores as the file's MetaDictionary, as the AAF SDK and pyaaf2 do. Avid's extensions (aaf2/model/ext)
# are left out. Properties without a fixed local id get dynamic ones from 0xFFFF down, in definition order, as pyaaf2 and
# the SDK assign them.
#
# Usage (after scripts/setup-pyaaf2.py): engine/artifacts/pyaaf2/bin/python -I scripts/aaf-model.py
from pathlib import Path

from aaf2 import metadict
from aaf2.model import classdefs, typedefs

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "engine" / "src" / "Anode.Interchange" / "Aaf" / "AafMetaModel.g.cs"


def guid(value):
    return f'"{str(value).lower()}"'


def name(value):
    return '"' + value.replace('"', '\\"') + '"'


def main():
    lines = []
    emit = lines.append
    emit("// <auto-generated>")
    emit("// Written by scripts/aaf-model.py from pyaaf2 1.7.1's AAF object model (MIT); do not edit.")
    emit("// </auto-generated>")
    emit("namespace Anode.Interchange.Aaf;")
    emit("")
    emit("static partial class AafMetaModel {")
    emit("    static readonly AafClassDef[] StandardClasses = [")
    next_pid = 0xFFFF
    for class_name, (auid, parent, concrete, props) in classdefs.classdefs.items():
        emit(f"        new({name(class_name)}, {guid(auid)}, {guid(parent) if parent else 'null'}, "
             f"{'true' if concrete else 'false'}, [")
        for prop_name, args in props.items():
            prop_auid, pid, type_auid, optional, unique = args[:5]
            if pid is None:
                pid = next_pid
                next_pid -= 1
            emit(f"            new({name(prop_name)}, {guid(prop_auid)}, 0x{pid:04X}, {guid(type_auid)}, "
                 f"{'true' if optional else 'false'}, {'true' if unique else 'false'}),")
        emit("        ]),")
    emit("    ];")
    emit("")
    emit("    static readonly AafTypeDef[] StandardTypes = [")
    t = typedefs
    for type_name, (auid, size, signed) in t.ints.items():
        emit(f"        new AafTypeDef.Integer({name(type_name)}, {guid(auid)}, {size}, {'true' if signed else 'false'}),")
    for type_name, (auid, element, elements) in t.enums.items():
        names = ", ".join(name(v) for v in elements.values())
        values = ", ".join(str(k) for k in elements.keys())
        emit(f"        new AafTypeDef.Enumeration({name(type_name)}, {guid(auid)}, {guid(element)}, [{names}], [{values}]),")
    for type_name, (auid, fields) in t.records.items():
        names = ", ".join(name(f[0]) for f in fields)
        types = ", ".join(guid(f[1]) for f in fields)
        emit(f"        new AafTypeDef.Record({name(type_name)}, {guid(auid)}, [{names}], [{types}]),")
    for type_name, (auid, element, count) in t.fixed_arrays.items():
        emit(f"        new AafTypeDef.FixedArray({name(type_name)}, {guid(auid)}, {guid(element)}, {count}),")
    for type_name, (auid, element) in t.var_arrays.items():
        emit(f"        new AafTypeDef.VariableArray({name(type_name)}, {guid(auid)}, {guid(element)}),")
    for type_name, (auid, renamed) in t.renames.items():
        emit(f"        new AafTypeDef.Rename({name(type_name)}, {guid(auid)}, {guid(renamed)}),")
    for type_name, (auid, element) in t.strings.items():
        emit(f"        new AafTypeDef.String({name(type_name)}, {guid(auid)}, {guid(element)}),")
    for type_name, auid in t.streams.items():
        emit(f"        new AafTypeDef.Stream({name(type_name)}, {guid(auid)}),")
    for type_name, auid in t.opaques.items():
        emit(f"        new AafTypeDef.Opaque({name(type_name)}, {guid(auid)}),")
    for type_name, (auid, elements) in t.extenums.items():
        names = ", ".join(name(v) for v in elements.values())
        values = ", ".join(guid(k) for k in elements.keys())
        emit(f"        new AafTypeDef.ExtendibleEnumeration({name(type_name)}, {guid(auid)}, [{names}], [{values}]),")
    for type_name, auid in t.chars.items():
        emit(f"        new AafTypeDef.Character({name(type_name)}, {guid(auid)}),")
    for type_name, (auid, size) in t.generic_chars.items():
        emit(f"        new AafTypeDef.GenericCharacter({name(type_name)}, {guid(auid)}, {size}),")
    for type_name, auid in t.indirects.items():
        emit(f"        new AafTypeDef.Indirect({name(type_name)}, {guid(auid)}),")
    for type_name, (auid, element) in t.sets.items():
        emit(f"        new AafTypeDef.Set({name(type_name)}, {guid(auid)}, {guid(element)}),")
    for type_name, (auid, target) in t.strongrefs.items():
        emit(f"        new AafTypeDef.StrongReference({name(type_name)}, {guid(auid)}, {guid(target)}),")
    for type_name, (auid, target, path) in t.weakrefs.items():
        steps = ", ".join(guid(p) for p in path)
        emit(f"        new AafTypeDef.WeakReference({name(type_name)}, {guid(auid)}, {guid(target)}, [{steps}]),")
    emit("    ];")
    emit("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


assert metadict  # the model's root classes (Root, its two properties) are written by hand in AafMetaModel.cs
main()
