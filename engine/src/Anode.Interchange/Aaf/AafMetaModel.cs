using System.Collections.Frozen;

namespace Anode.Interchange.Aaf;

/// <summary>A class of the AAF object model: its name, AUID, parent class, whether it is concrete, and its properties.</summary>
sealed record AafClassDef(string Name, string Auid, string? Parent, bool Concrete, AafPropertyDef[] Properties);

/// <summary>A property definition: name, AUID, local id (pid), type AUID, optional, and whether it is the unique key.</summary>
sealed record AafPropertyDef(string Name, string Auid, ushort Pid, string Type, bool Optional, bool Unique);

/// <summary>A type definition of the AAF object model, by kind.</summary>
abstract record AafTypeDef(string Name, string Auid) {
    public sealed record Integer(string Name, string Auid, int Size, bool Signed) : AafTypeDef(Name, Auid);

    public sealed record Enumeration(string Name, string Auid, string Element, string[] Names, long[] Values)
        : AafTypeDef(Name, Auid);

    public sealed record Record(string Name, string Auid, string[] Names, string[] Types) : AafTypeDef(Name, Auid);

    public sealed record FixedArray(string Name, string Auid, string Element, int Count) : AafTypeDef(Name, Auid);

    public sealed record VariableArray(string Name, string Auid, string Element) : AafTypeDef(Name, Auid);

    public sealed record Rename(string Name, string Auid, string Renamed) : AafTypeDef(Name, Auid);

    public sealed record String(string Name, string Auid, string Element) : AafTypeDef(Name, Auid);

    public sealed record Stream(string Name, string Auid) : AafTypeDef(Name, Auid);

    public sealed record Opaque(string Name, string Auid) : AafTypeDef(Name, Auid);

    public sealed record ExtendibleEnumeration(string Name, string Auid, string[] Names, string[] Values)
        : AafTypeDef(Name, Auid);

    public sealed record Character(string Name, string Auid) : AafTypeDef(Name, Auid);

    public sealed record GenericCharacter(string Name, string Auid, int Size) : AafTypeDef(Name, Auid);

    public sealed record Indirect(string Name, string Auid) : AafTypeDef(Name, Auid);

    public sealed record Set(string Name, string Auid, string Element) : AafTypeDef(Name, Auid);

    public sealed record StrongReference(string Name, string Auid, string Target) : AafTypeDef(Name, Auid);

    public sealed record WeakReference(string Name, string Auid, string Target, string[] Path) : AafTypeDef(Name, Auid);
}

/// <summary>
///     The standard AAF object model (AafMetaModel.g.cs, generated by <c>scripts/aaf-model.py</c>) and the MetaDictionary
///     the writer stores from it: every class definition (with its property definitions) and every type definition, as
///     the AAF SDK and pyaaf2 write them, so a reader can interpret the file from the file alone.
/// </summary>
static partial class AafMetaModel {
    static readonly Guid ClassDefinition = new("0d010101-0201-0000-060e-2b3402060101");
    static readonly Guid PropertyDefinition = new("0d010101-0202-0000-060e-2b3402060101");
    static readonly Guid MetaDictionaryClass = new("0d010101-0225-0000-060e-2b3402060101");
    static readonly AafWeakTarget Classes = new([0x0001, 0x0003], 0x0005);
    static readonly AafWeakTarget Types = new([0x0001, 0x0004], 0x0005);

    public static IReadOnlyList<AafClassDef> All => StandardClasses;

    public static string PropertyName(ushort pid) =>
        Lookup.Names.TryGetValue(pid, out var name)
            ? name
            : throw new InvalidOperationException($"No property {pid:X4}.");

    /// <summary>The MetaDictionary object: the class definitions, then the type definitions.</summary>
    public static AafObject MetaDictionary() =>
        new AafObject(MetaDictionaryClass)
            .Set(0x0003, 0x0005, StandardClasses.Select(static c => (Key(c.Auid), ClassObject(c))))
            .Set(0x0004, 0x0005, StandardTypes.Select(static t => (Key(t.Auid), TypeObject(t))));

    static byte[] Key(string auid) => AafEncoding.Auid(new(auid));

    static AafObject ClassObject(AafClassDef c) =>
        new AafObject(ClassDefinition)
            .Data(0x0006, AafEncoding.String(c.Name))
            .Data(0x0005, Key(c.Auid))
            .Data(0x000A, AafEncoding.Bool(c.Concrete))
            .Weak(0x0008, Classes, Key(c.Parent ?? c.Auid))
            .Set(
                0x0009,
                0x0005,
                c.Properties.Select(static p => (Key(p.Auid),
                        new AafObject(PropertyDefinition)
                            .Data(0x0006, AafEncoding.String(p.Name))
                            .Data(0x000C, AafEncoding.Bool(p.Optional))
                            .Data(0x000E, AafEncoding.Bool(p.Unique))
                            .Data(0x000D, AafEncoding.UInt16(p.Pid))
                            .Data(0x0005, Key(p.Auid))
                            .Data(0x000B, Key(p.Type)))
                )
            );

    static AafObject TypeObject(AafTypeDef t) {
        var (classId, fill) = t switch {
            AafTypeDef.Integer i => ("0204", (Action<AafObject>)(o => o.Data(0x000F, AafEncoding.UInt8((byte)i.Size))
                .Data(0x0010, AafEncoding.Bool(i.Signed)))),
            AafTypeDef.StrongReference s => ("0205", o => o.Weak(0x0011, Classes, Key(s.Target))),
            AafTypeDef.WeakReference w => ("0206", o => o.Weak(0x0012, Classes, Key(w.Target))
                .Data(0x0013, AafEncoding.Auids(w.Path.Select(static p => new Guid(p))))),
            AafTypeDef.Enumeration e => ("0207", o => o.Weak(0x0014, Types, Key(e.Element))
                .Data(0x0015, AafEncoding.Strings(e.Names))
                .Data(0x0016, AafEncoding.Int64s(e.Values))),
            AafTypeDef.FixedArray f => ("0208", o => o.Weak(0x0017, Types, Key(f.Element))
                .Data(0x0018, AafEncoding.UInt32((uint)f.Count))),
            AafTypeDef.VariableArray v => ("0209", o => o.Weak(0x0019, Types, Key(v.Element))),
            AafTypeDef.Set s => ("020a", o => o.Weak(0x001A, Types, Key(s.Element))),
            AafTypeDef.String s => ("020b", o => o.Weak(0x001B, Types, Key(s.Element))),
            AafTypeDef.Stream => ("020c", static _ => { }),
            AafTypeDef.Record r => ("020d", o => o.WeakVector(0x001C, Types, r.Types.Select(Key))
                .Data(0x001D, AafEncoding.Strings(r.Names))),
            AafTypeDef.Rename r => ("020e", o => o.Weak(0x001E, Types, Key(r.Renamed))),
            AafTypeDef.ExtendibleEnumeration e => ("0220", o => o.Data(0x001F, AafEncoding.Strings(e.Names))
                .Data(0x0020, AafEncoding.Auids(e.Values.Select(static v => new Guid(v))))),
            AafTypeDef.Indirect => ("0221", static _ => { }),
            AafTypeDef.Opaque => ("0222", static _ => { }),
            AafTypeDef.Character => ("0223", static _ => { }),
            AafTypeDef.GenericCharacter g => ("generic",
                o => o.Data(GenericCharacterSizePid, AafEncoding.UInt8((byte)g.Size))),
            _ => throw new InvalidOperationException(t.Name)
        };
        var item = new AafObject(
            classId == "generic"
                ? new("0e040101-0000-0000-060e-2b3402060101")
                : new($"0d010101-{classId}-0000-060e-2b3402060101")
        );
        item.Data(0x0006, AafEncoding.String(t.Name)).Data(0x0005, Key(t.Auid));
        fill(item);
        return item;
    }

    static ushort GenericCharacterSizePid =>
        StandardClasses.First(static c => c.Name == "TypeDefinitionGenericCharacter").Properties[0].Pid;

    /// <summary>The names of every property by pid (the root's two included), for storage names.</summary>
    static class Lookup {
        public static readonly FrozenDictionary<ushort, string> Names = StandardClasses
            .SelectMany(static c => c.Properties)
            .Select(static p => KeyValuePair.Create(p.Pid, p.Name))
            .Append(KeyValuePair.Create((ushort)0x0001, "MetaDictionary"))
            .Append(KeyValuePair.Create((ushort)0x0002, "Header"))
            .DistinctBy(static p => p.Key)
            .ToFrozenDictionary();
    }
}
